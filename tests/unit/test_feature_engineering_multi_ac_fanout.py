def _two_ac_clean_content(req: TestableRequirement) -> str:
    ac1, ac2 = req.acceptance_criteria
    return f"""@smoke @{ac1.criterion_id} @SCN-PENDING
Scenario: User receives a password reset email
  Given a registered user requests a password reset
  When the reset request is submitted
  Then a reset email is sent

@regression @{ac2.criterion_id} @SCN-PENDING
Scenario: Expired reset link is rejected
  Given a user has an expired password reset link
  When the user opens the reset link
  Then the system rejects the expired link
"""


def _three_ac_clean_content(req: TestableRequirement) -> str:
    ac1, ac2, ac3 = req.acceptance_criteria
    # @balance is authored on every scenario (a genuine, deliberate
    # cross-scenario homogenous functional tag); @security only on the
    # second, so it must stay scenario-level.
    return f"""@balance @{ac1.criterion_id} @SCN-PENDING
Scenario: User views current account balance
  Given a logged-in user with an active account
  When the user opens the balance view
  Then the current account balance is displayed

@balance @security @{ac2.criterion_id} @SCN-PENDING
Scenario: Balance is hidden after repeated failed PIN attempts
  Given a user has entered an incorrect PIN three times
  When the user attempts to view the balance again
  Then the balance is hidden and re-authentication is required

@balance @{ac3.criterion_id} @SCN-PENDING
Scenario Outline: Balance rounds correctly at the minimum currency unit boundary
  Given an account balance of "<raw_balance>"
  When the balance is displayed
  Then the displayed balance is "<rounded_balance>"
  Examples:
    | raw_balance | rounded_balance |
    | 10.005 | 10.01 |
    | 10.004 | 10.00 |
"""


def _polarity_full_clean_content(req: TestableRequirement) -> str:
    (ac,) = req.acceptance_criteria
    # Both scenarios cover the SAME (only) AC -- one for the positive path,
    # one (an outline) for the negative/boundary paths the polarity hints
    # call for. @login is on both scenarios too, so both @login and the AC
    # tag are genuinely homogenous here and correctly hoist.
    return f"""@login @{ac.criterion_id} @SCN-PENDING
Scenario: Successful login within lockout policy
  Given a user with no prior failed login attempts
  When the user logs in with correct credentials
  Then the login succeeds

@login @{ac.criterion_id} @SCN-PENDING
Scenario Outline: Login attempts beyond the lockout boundary are rejected
  Given a user has "<failed_attempts>" prior failed login attempts
  When the user attempts to log in again
  Then the outcome is "<expected_outcome>"
  Examples:
    | failed_attempts | expected_outcome |
    | 4 | rejected |
    | 5 | locked_out |
"""


class TestTwoAndThreeAcFanOut:
    def test_two_ac_requirement_produces_two_correctly_tagged_scenarios(
        self, tmp_path: Path
    ) -> None:
        req = _two_ac_requirement()
        raw = _two_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        assert result.lint_result.is_clean
        assert len(result.scenarios) == 2
        assert result.fully_covered
        assert all(result.acceptance_criteria_coverage.values())
        scn_ids = {s.scn_id for s in result.scenarios}
        assert len(scn_ids) == 2  # distinct

        print("=== 2-AC assembled .feature ===")
        print(result.content)

    def test_three_ac_requirement_produces_three_correctly_tagged_scenarios(
        self, tmp_path: Path
    ) -> None:
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        assert result.lint_result.is_clean
        assert len(result.scenarios) == 3
        assert result.fully_covered
        assert all(result.acceptance_criteria_coverage.values())
        scn_ids = {s.scn_id for s in result.scenarios}
        assert len(scn_ids) == 3  # distinct

        print("=== 3-AC assembled .feature ===")
        print(result.content)

    def test_polarity_full_ac_two_scenarios_share_one_ac_tag(self, tmp_path: Path) -> None:
        req = _polarity_full_ac_requirement()
        raw = _polarity_full_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        assert result.lint_result.is_clean
        assert len(result.scenarios) == 2
        assert result.fully_covered
        # Both scenarios reference the requirement's one AC.
        (ac,) = req.acceptance_criteria
        assert all(ac.criterion_id in s.ac_ids for s in result.scenarios)
        scn_ids = {s.scn_id for s in result.scenarios}
        assert len(scn_ids) == 2  # distinct even though they share an AC

        print("=== single-AC, two-scenario assembled .feature ===")
        print(result.content)


class TestHoistFiresOnlyOnGenuineHomogeneity:
    def test_three_ac_case_ac_tags_do_not_wrongly_hoist(self, tmp_path: Path) -> None:
        """3 distinct ACs, one per scenario: none of the @AC-* tags are
        present on every scenario, so none may hoist -- proving the hoist
        does not fire merely because a feature has several AC tags."""
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        feature_tag_line = result.content.splitlines()[0]
        for ac in req.acceptance_criteria:
            assert f"@{ac.criterion_id}" not in feature_tag_line
            assert f"@{ac.criterion_id}" in result.content  # still present, at scenario level

    def test_three_ac_case_functional_tag_on_all_scenarios_still_hoists(
        self, tmp_path: Path
    ) -> None:
        """@balance is authored on all three scenarios in the same fixture
        above -- contrasting proof that genuine homogeneity still hoists in
        a real multi-scenario (not just single-scenario) feature."""
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        feature_tag_line = result.content.splitlines()[0]
        assert "@balance" in feature_tag_line
        assert "@security" not in feature_tag_line  # only on one scenario -- must not hoist

    def test_single_ac_shared_by_two_scenarios_correctly_hoists(self, tmp_path: Path) -> None:
        """The polarity fixture: with only one AC and both scenarios
        covering it, the AC tag IS genuinely homogenous (present on every
        scenario) and correctly hoists -- the mirror-image case of the two
        tests above."""
        req = _polarity_full_ac_requirement()
        raw = _polarity_full_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )

        (ac,) = req.acceptance_criteria
        feature_tag_line = result.content.splitlines()[0]
        assert f"@{ac.criterion_id}" in feature_tag_line
        assert "@login" in feature_tag_line


class TestScnIdUniquenessAndStability:
    def test_three_scenarios_yield_three_distinct_scn_ids(self, tmp_path: Path) -> None:
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )
        scn_ids = [s.scn_id for s in result.scenarios]
        assert len(scn_ids) == len(set(scn_ids)) == 3

    def test_same_fixture_yields_the_same_scn_set_across_two_independent_runs(
        self, tmp_path: Path
    ) -> None:
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        first = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )
        second = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )
        assert {s.scn_id for s in first.scenarios} == {s.scn_id for s in second.scenarios}
        assert first.content == second.content

    def test_reordering_scenarios_in_raw_content_does_not_reassign_scn_ids(
        self, tmp_path: Path
    ) -> None:
        req = _three_ac_requirement()
        ac1, ac2, ac3 = req.acceptance_criteria
        forward = _three_ac_clean_content(req)
        # Same three scenarios, reversed order in the raw text.
        reversed_order = f"""@balance @{ac3.criterion_id} @SCN-PENDING
Scenario Outline: Balance rounds correctly at the minimum currency unit boundary
  Given an account balance of "<raw_balance>"
  When the balance is displayed
  Then the displayed balance is "<rounded_balance>"
  Examples:
    | raw_balance | rounded_balance |
    | 10.005 | 10.01 |
    | 10.004 | 10.00 |

@balance @security @{ac2.criterion_id} @SCN-PENDING
Scenario: Balance is hidden after repeated failed PIN attempts
  Given a user has entered an incorrect PIN three times
  When the user attempts to view the balance again
  Then the balance is hidden and re-authentication is required

@balance @{ac1.criterion_id} @SCN-PENDING
Scenario: User views current account balance
  Given a logged-in user with an active account
  When the user opens the balance view
  Then the current account balance is displayed
"""
        forward_result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: forward}), features_root=tmp_path
        )
        reversed_result = generate_feature_file(
            req,
            StubFeatureContentGenerator({req.requirement_id: reversed_order}),
            features_root=tmp_path,
        )
        forward_by_name = {s.name: s.scn_id for s in forward_result.scenarios}
        reversed_by_name = {s.name: s.scn_id for s in reversed_result.scenarios}
        assert forward_by_name == reversed_by_name


class TestAcCoverageAcrossFanOut:
    def test_three_ac_coverage_maps_each_ac_to_its_own_scenario(self, tmp_path: Path) -> None:
        req = _three_ac_requirement()
        raw = _three_ac_clean_content(req)
        result = generate_feature_file(
            req, StubFeatureContentGenerator({req.requirement_id: raw}), features_root=tmp_path
        )
        ac1, ac2, ac3 = req.acceptance_criteria
        by_ac = {s.ac_ids[0]: s.scn_id for s in result.scenarios}
