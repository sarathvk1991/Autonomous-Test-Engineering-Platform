"""Multi-AC fan-out: proving the ALREADY-GENERIC generator core against
authored, multi-scenario content.

*** SYNTHETIC FIXTURES -- READ BEFORE TRUSTING ANY NUMBER IN THIS FILE ***
Every `TestableRequirement` and every piece of raw scenario content in this
module is HAND-CONSTRUCTED. The requirements are built through the contract's
own constructor (`build_testable_requirement`), so their ids are real,
platform-assigned, content-addressed values -- but the underlying content
(titles, acceptance criteria, and every scenario) is authored by this test
file, not emitted by Layer 1 and not generated by a live model. This is
legitimate as GENERATOR-CORE test fixture material (exactly like every other
`_requirement()`/raw-content pair in `test_feature_engineering_generation_core.py`),
and it is NOT real-world evidence: it must never be cited as a Layer 1
emission or used to estimate real model failure rates. The live-sampling
task (CAP context) already established the real corpus is single-AC-only and
content-stable against the one available evidence set -- these fixtures fill
exactly the multi-AC/multi-scenario gap that corpus cannot reach.

Why no core code changes were needed
-------------------------------------
Pre-flight for this task found `feature_engineering/generation/assembler.py`
already generic over an arbitrary number of scenarios and an arbitrary
per-scenario `@AC-*` tag set: it discovers scenarios by parsing whatever the
content generator returns (`for child in source.feature["children"]`), mints
one `@SCN-*` per scenario found, tracks AC coverage as a floor ("every AC-*
has >=1 mapped SCN-*", ADR-0043 D5's own CP2-gate wording), and computes the
homogeneity hoist over however many scenarios exist. Neither ADR-0043 D2/D5
nor the governed `generate_feature` v1.1.0 prompt specify an exact
scenario-per-AC ratio -- the prompt's own TASK section says only "every
acceptance criterion must be exercised by at least one scenario" and its TAG
PLACEMENT section explicitly permits the inverse too ("A scenario may carry
more than one ac_id tag if it exercises more than one criterion"). Fan-out
granularity is therefore a content-generation-time (model) decision under a
coverage floor, not a platform mechanism -- there was nothing to build. This
module exercises that already-generic mechanism against multi-scenario
content it had never been run against (2-AC, 3-AC, a single AC covered by
two scenarios, and deliberately-malformed content), closing a TEST-COVERAGE
gap, not a functionality gap.
"""

